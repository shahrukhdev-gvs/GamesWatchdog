"""
migrate_to_new_supabase.py — one-off copy of all Play Store Watchdog data from
the old Supabase project into a new one built with 00-new-project-schema.sql.

Credentials come from .env only (see .env.example):
    OLD_SUPABASE_URL, OLD_SUPABASE_KEY   service_role key of the old project
    NEW_SUPABASE_URL, NEW_SUPABASE_KEY   service_role key of the new project
    NEW_USER_PASSWORD                    initial password for every migrated login

Both clients use the service_role key, so RLS is bypassed and auth.uid() is
NULL: every row written here sets user_id explicitly.

What it does
  1. Reads profiles from the old project.
  2. Creates each user in the new project through the Auth admin API
     (<username>@watchdog.local, email_confirm=True, NEW_USER_PASSWORD).
  3. Maps old user_id -> new user_id by username.
  4. Copies profiles, user_settings, studios, teams, ad_network_ids,
     developers, apps, change_log, firebase_games in that order. Integer ids are
     regenerated by the new database; studio_id, team_id, developer_id, app_id
     and firebase_games.added_by are rewritten through old-id -> new-id maps.
     Rows whose user_id is NULL in the old project inherit their owner: an app
     from its developer, a change_log row from its app (or its developer if it
     has no app). They are skipped only if that parent is missing or has no
     owner either.

Idempotent: every row is matched against what is already in the new project by
its natural key (the same columns the unique indexes use), so a second run
inserts nothing. change_log has no natural key, so it is matched on
(user, event, timestamp, app, developer, run, package) and only missing
occurrences are inserted.

Usage
    python migrate_to_new_supabase.py --dry-run          # read both, write nothing
    python migrate_to_new_supabase.py                    # do it
    python migrate_to_new_supabase.py --skip-change-log  # leave change_log out
"""

import argparse
import os
import sys
from collections import Counter, defaultdict
from datetime import datetime, timezone
from pathlib import Path

import httpx
from dotenv import load_dotenv
from supabase import create_client

BATCH_SIZE = 500
PAGE_SIZE = 1000
USERNAME_DOMAIN = "watchdog.local"  # must match auth.py
ENV_VARS = ("OLD_SUPABASE_URL", "OLD_SUPABASE_KEY",
            "NEW_SUPABASE_URL", "NEW_SUPABASE_KEY", "NEW_USER_PASSWORD")
TABLE_ORDER = ("auth users", "profiles", "user_settings", "studios", "teams",
               "ad_network_ids", "developers", "apps", "change_log", "firebase_games")


def username_to_email(username):
    """Same convention as auth.username_to_email (not imported: auth.py needs streamlit)."""
    username = (username or "").strip().lower()
    return f"{username}@{USERNAME_DOMAIN}" if username else ""


def norm_ts(value):
    """Timestamps as one canonical UTC string, so both projects compare equal."""
    if not value:
        return value
    try:
        d = datetime.fromisoformat(str(value).replace("Z", "+00:00"))
    except ValueError:
        return value
    if d.tzinfo is None:
        d = d.replace(tzinfo=timezone.utc)
    return d.astimezone(timezone.utc).isoformat()


class Migration:
    def __init__(self, env, dry_run):
        self.dry_run = dry_run
        self.old = create_client(env["OLD_SUPABASE_URL"], env["OLD_SUPABASE_KEY"])
        self.new = create_client(env["NEW_SUPABASE_URL"], env["NEW_SUPABASE_KEY"])
        self.password = env["NEW_USER_PASSWORD"]
        self.new_columns = self._table_columns(env["NEW_SUPABASE_URL"], env["NEW_SUPABASE_KEY"])
        self.stats = defaultdict(Counter)   # table -> read / inserted / skipped
        self.notes = Counter()              # (table, message) -> occurrences
        self.user_map = {}                  # old user_id -> new user_id
        self.id_maps = {}                   # table -> {old id -> new id}
        self.old_owner = defaultdict(dict)  # table -> {old id -> old owner, after inheritance}

    # ---------------------------------------------------------------- helpers
    def note(self, table, message, n=1):
        self.notes[(table, message)] += n

    @staticmethod
    def _table_columns(url, key):
        """Column names per table in the new project, from PostgREST's OpenAPI spec."""
        try:
            r = httpx.get(f"{url.rstrip('/')}/rest/v1/",
                          headers={"apikey": key, "Authorization": f"Bearer {key}"},
                          timeout=30)
            r.raise_for_status()
            defs = r.json().get("definitions", {})
            return {name: set(d.get("properties", {})) for name, d in defs.items()}
        except Exception as e:  # message only; never the request headers
            print(f"warning: could not read the new project's schema ({type(e).__name__}); "
                  "copying old columns unfiltered")
            return None

    def check_new_schema(self, tables):
        if self.new_columns is None:
            return
        missing = [t for t in tables if t not in self.new_columns]
        if missing:
            sys.exit("The new project is missing tables: " + ", ".join(missing)
                     + ". Run 00-new-project-schema.sql there first.")

    @staticmethod
    def fetch_all(client, table, columns="*", order="id"):
        rows, start = [], 0
        while True:
            page = (client.table(table).select(columns).order(order)
                    .range(start, start + PAGE_SIZE - 1).execute().data)
            if not page:
                return rows
            rows.extend(page)
            start += len(page)

    def insert_batches(self, table, payloads):
        """Insert in batches of BATCH_SIZE; returns the inserted rows (with new ids)."""
        if self.dry_run:
            return []
        out = []
        for i in range(0, len(payloads), BATCH_SIZE):
            out.extend(self.new.table(table).insert(payloads[i:i + BATCH_SIZE]).execute().data)
        return out

    def base_payload(self, table, row):
        """Old row minus its id and minus columns the new table doesn't have."""
        payload = {k: v for k, v in row.items() if k != "id"}
        cols = self.new_columns.get(table) if self.new_columns else None
        if cols is not None:
            dropped = sorted(k for k in payload if k not in cols)
            for k in dropped:
                payload.pop(k)
            if dropped:
                self.note(table, "old-only columns not copied: " + ", ".join(dropped))
        return payload

    def inherit_owner(self, table, row, parents):
        """Old owner for a row whose user_id is NULL, taken from the first parent it
        references: parents is ((column, parent_table), ...) in order of preference.
        None (with the reason noted) if the parent is missing or has no owner."""
        for column, parent in parents:
            parent_id = row.get(column)
            if parent_id is None:
                continue
            label = parent.rstrip("s")
            owners = self.old_owner[parent]
            if parent_id not in owners:
                self.note(table, f"skipped: user_id NULL and its {label} is missing")
                return None
            if owners[parent_id] is None:
                self.note(table, f"skipped: user_id NULL and its {label} has no owner either")
                return None
            self.note(table, f"user_id was NULL; inherited from its {label}")
            return owners[parent_id]
        self.note(table, "skipped: user_id NULL and no parent to inherit from")
        return None

    def resolve_owner(self, table, row, payload, inherit_from):
        """Fill a NULL user_id from the parent and record the row's old owner.
        False if there is still no owner (already noted)."""
        if payload.get("user_id") is None and inherit_from:
            payload["user_id"] = self.inherit_owner(table, row, inherit_from)
            if payload["user_id"] is None:
                if "id" in row:
                    self.old_owner[table][row["id"]] = None
                return False
        if "id" in row:
            self.old_owner[table][row["id"]] = payload.get("user_id")
        return True

    def remap_owner(self, table, payload):
        """Rewrite user_id to the new project's id. False if the row has no migrated owner."""
        old_uid = payload.get("user_id")
        if old_uid is None:
            self.note(table, "skipped: user_id is NULL in the old project")
            return False
        new_uid = self.user_map.get(old_uid)
        if new_uid is None:
            self.note(table, "skipped: owner has no profile in the old project")
            return False
        payload["user_id"] = new_uid
        return True

    def remap_fk(self, table, payload, column, target):
        """Rewrite an integer foreign key through the target table's id map."""
        old_id = payload.get(column)
        if old_id is None:
            return
        new_id = self.id_maps[target].get(old_id)
        if new_id is None:
            self.note(table, f"{column} pointed at a {target} row that wasn't copied; set to NULL")
        payload[column] = new_id

    # ------------------------------------------------------------------ users
    def migrate_users(self):
        t = "auth users"
        profiles = self.fetch_all(self.old, "profiles", order="user_id")
        existing, page = {}, 1  # email -> new user id, for users already in the new project
        while True:
            batch = self.new.auth.admin.list_users(page=page, per_page=1000)
            for u in batch or []:
                if u.email:
                    existing[u.email.lower()] = u.id
            if not batch or len(batch) < 1000:
                break
            page += 1

        for p in profiles:
            self.stats[t]["read"] += 1
            email = username_to_email(p.get("username"))
            if not email:
                self.stats[t]["skipped"] += 1
                self.note(t, "skipped: profile has no username")
                continue
            if email in existing:
                self.user_map[p["user_id"]] = existing[email]
                self.stats[t]["skipped"] += 1
                continue
            if self.dry_run:
                new_id = f"dry-run:{email}"
            else:
                try:
                    created = self.new.auth.admin.create_user({
                        "email": email,
                        "password": self.password,
                        "email_confirm": True,
                    })
                    new_id = created.user.id
                except Exception as e:
                    # Never echo the request; the API's error text holds no secrets.
                    sys.exit(f"Could not create auth user {email}: {e}")
            existing[email] = new_id
            self.user_map[p["user_id"]] = new_id
            self.stats[t]["inserted"] += 1
        return profiles

    # ----------------------------------------------------------- keyed tables
    def copy_keyed(self, table, natural_key, existing_columns, *, old_rows=None,
                   order="id", fks=(), user_fks=(), inherit_from=(), has_id=True):
        """Copy a table whose rows have a natural key; builds self.id_maps[table]."""
        if old_rows is None:
            old_rows = self.fetch_all(self.old, table, order=order)
        existing = {natural_key(r): r.get("id")
                    for r in self.fetch_all(self.new, table, existing_columns, order=order)}
        id_map, planned, payloads = {}, {}, []
        slot = {}  # natural key -> (index in payloads, owner was inherited?)

        for row in old_rows:
            self.stats[table]["read"] += 1
            payload = self.base_payload(table, row)
            if (not self.resolve_owner(table, row, payload, inherit_from)
                    or not self.remap_owner(table, payload)):
                self.stats[table]["skipped"] += 1
                continue
            for column, target in fks:
                self.remap_fk(table, payload, column, target)
            for column in user_fks:
                if payload.get(column) is not None:
                    new_uid = self.user_map.get(payload[column])
                    if new_uid is None:
                        self.note(table, f"{column} user wasn't migrated; set to NULL")
                    payload[column] = new_uid

            key = natural_key(payload)
            if key in existing:
                if has_id:
                    id_map[row["id"]] = existing[key]
                self.stats[table]["skipped"] += 1
                continue
            inherited = row.get("user_id") is None
            if key in planned:  # duplicate inside the old data; both old ids map to one new row
                planned[key].append(row.get("id"))
                self.stats[table]["skipped"] += 1
                index, kept_inherited = slot[key]
                if kept_inherited and not inherited:
                    # Prefer the row that had its own owner over one that inherited it.
                    payloads[index] = payload
                    slot[key] = (index, False)
                    self.note(table, "skipped: duplicate (same natural key); kept the row "
                                     "with its own user_id, dropped the one that inherited it")
                elif inherited and not kept_inherited:
                    self.note(table, "skipped: duplicate (same natural key); dropped the row "
                                     "that inherited its user_id, kept the one with its own")
                else:
                    self.note(table, "skipped: duplicate of another old row (same natural key)")
                continue
            planned[key] = [row.get("id")]
            slot[key] = (len(payloads), inherited)
            payloads.append(payload)

        inserted = self.insert_batches(table, payloads)
        self.stats[table]["inserted"] += len(payloads)
        if has_id:
            if self.dry_run:
                new_ids = {k: f"dry-run:{table}:{ids[0]}" for k, ids in planned.items()}
            else:
                new_ids = {natural_key(r): r["id"] for r in inserted}
            for key, old_ids in planned.items():
                for old_id in old_ids:
                    id_map[old_id] = new_ids.get(key)
            self.id_maps[table] = id_map

    # ------------------------------------------------------------- change_log
    @staticmethod
    def change_key(r):
        return (r.get("user_id"), r.get("event_type"), norm_ts(r.get("detected_at")),
                r.get("app_id"), r.get("developer_id"), r.get("run_id"), r.get("package_name"))

    def copy_change_log(self):
        t = "change_log"
        old_rows = self.fetch_all(self.old, t)
        present = Counter(self.change_key(r) for r in self.fetch_all(
            self.new, t, "id,user_id,event_type,detected_at,app_id,developer_id,run_id,package_name"))
        payloads = []
        for row in old_rows:
            self.stats[t]["read"] += 1
            payload = self.base_payload(t, row)
            inherit_from = (("app_id", "apps"), ("developer_id", "developers"))
            if (not self.resolve_owner(t, row, payload, inherit_from)
                    or not self.remap_owner(t, payload)):
                self.stats[t]["skipped"] += 1
                continue
            self.remap_fk(t, payload, "app_id", "apps")
            self.remap_fk(t, payload, "developer_id", "developers")
            key = self.change_key(payload)
            if present[key] > 0:      # one existing copy absorbs one old occurrence
                present[key] -= 1
                self.stats[t]["skipped"] += 1
                continue
            payloads.append(payload)
        self.insert_batches(t, payloads)
        self.stats[t]["inserted"] += len(payloads)

    # -------------------------------------------------------------------- run
    def run(self, skip_change_log):
        tables = [t for t in TABLE_ORDER[1:] if not (skip_change_log and t == "change_log")]
        self.check_new_schema(tables)

        profiles = self.migrate_users()

        self.copy_keyed("profiles", lambda r: r.get("user_id"), "user_id",
                        old_rows=profiles, order="user_id", has_id=False)
        self.copy_keyed("user_settings", lambda r: r.get("user_id"), "user_id",
                        order="user_id", has_id=False)
        self.copy_keyed("studios", lambda r: (r.get("user_id"), r.get("name")), "id,user_id,name")
        self.copy_keyed("teams", lambda r: (r.get("user_id"), r.get("name")), "id,user_id,name")
        self.copy_keyed("ad_network_ids", lambda r: (r.get("user_id"), r.get("account_id")),
                        "id,user_id,account_id", fks=(("studio_id", "studios"),))
        # dev_id is nullable and NULLs don't collide in the unique index, so fall back
        # to name + URL for developers without one.
        self.copy_keyed("developers",
                        lambda r: ((r.get("user_id"), "dev_id", r.get("dev_id")) if r.get("dev_id")
                                   else (r.get("user_id"), "name", r.get("name"), r.get("developer_url"))),
                        "id,user_id,dev_id,name,developer_url",
                        fks=(("studio_id", "studios"), ("team_id", "teams")))
        self.copy_keyed("apps", lambda r: (r.get("user_id"), r.get("package_name")),
                        "id,user_id,package_name", fks=(("developer_id", "developers"),),
                        inherit_from=(("developer_id", "developers"),))
        if skip_change_log:
            self.stats["change_log"]  # keep the row in the summary
            self.note("change_log", "not copied (--skip-change-log)")
        else:
            self.copy_change_log()
        # package_name is unique across the whole table, whoever owns it
        self.copy_keyed("firebase_games", lambda r: r.get("package_name"), "id,package_name",
                        user_fks=("added_by",))

    def print_summary(self):
        mode = "DRY RUN: nothing was written" if self.dry_run else "LIVE RUN"
        head = "Would insert" if self.dry_run else "Inserted"
        print(f"\n{mode}\n")
        print(f"{'Table':<16}{'Read':>8}{head:>14}{'Skipped':>10}")
        print("-" * 48)
        totals = Counter()
        for t in TABLE_ORDER:
            if t not in self.stats:
                continue
            s = self.stats[t]
            totals.update(s)
            print(f"{t:<16}{s['read']:>8}{s['inserted']:>14}{s['skipped']:>10}")
        print("-" * 48)
        print(f"{'total':<16}{totals['read']:>8}{totals['inserted']:>14}{totals['skipped']:>10}")
        print("\nSkipped = already in the new project, unless a note below says otherwise.")
        if self.notes:
            print("\nNotes:")
            for (table, msg), n in sorted(self.notes.items()):
                print(f"  {table}: {msg} (x{n})")


def load_env():
    load_dotenv(Path(__file__).with_name(".env"))
    env = {k: (os.environ.get(k) or "").strip() for k in ENV_VARS}
    missing = [k for k, v in env.items() if not v]
    if missing:
        sys.exit("Missing in .env: " + ", ".join(missing))  # names only, never values
    if env["OLD_SUPABASE_URL"].rstrip("/").lower() == env["NEW_SUPABASE_URL"].rstrip("/").lower():
        sys.exit("OLD_SUPABASE_URL and NEW_SUPABASE_URL are the same project; refusing to run.")
    return env


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--dry-run", action="store_true",
                    help="read both projects and report what would be copied; write nothing")
    ap.add_argument("--skip-change-log", action="store_true",
                    help="don't copy change_log (the largest table)")
    args = ap.parse_args()

    m = Migration(load_env(), args.dry_run)
    try:
        m.run(args.skip_change_log)
    except SystemExit:
        m.print_summary()
        raise
    except Exception as e:
        m.print_summary()
        sys.exit(f"\nStopped with an error: {type(e).__name__}: {e}\n"
                 "Rows already inserted stay; re-running continues where it left off.")
    m.print_summary()


if __name__ == "__main__":
    main()
